"""Turn a HostResult into a Markdown report and a JSON dump."""

from __future__ import annotations

import json
from pathlib import Path

from soul_toolkit import __version__
from soul_toolkit.core.models import HostResult
from soul_toolkit.recon import leads as leads_mod

_BADGE = {"high": "🔴 HIGH", "medium": "🟠 MEDIUM", "low": "🟡 LOW", "info": "🔵 INFO"}


def _cell(text: str) -> str:
    return (text or "-").replace("|", "\\|").replace("\n", " ")


def _fmt_duration(seconds: float) -> str:
    m, s = divmod(round(seconds), 60)
    return f"{m}m {s:02d}s" if m else f"{s}s"


def _fence(text: str, lang: str = "") -> str:
    fence = "````" if "```" in text else "```"
    return f"{fence}{lang}\n{text.rstrip()}\n{fence}"


def _indent(text: str, prefix: str) -> str:
    return "\n".join(prefix + line for line in text.splitlines())


def render_markdown(r: HostResult) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# Recon report: `{r.target}`")
    add("")
    add(f"> Generated by soul-toolkit v{__version__} - authorized testing only.")
    add("")
    add("| | |")
    add("|---|---|")
    add(f"| Target | `{r.target}` |")
    if r.address and r.address != r.target:
        add(f"| Address | `{r.address}` |")
    if r.hostnames:
        add(f"| Hostnames | {', '.join(r.hostnames)} |")
    add(f"| Host status | {r.status} |")
    if r.os_guess:
        add(f"| OS guess | {_cell(r.os_guess)} |")
    add(f"| Open ports | {len(r.services)} |")
    add(f"| Started | {r.started} |")
    add(f"| Duration | {_fmt_duration(r.duration)} |")
    add("")

    # Summary by severity
    findings = r.sorted_findings()
    counts = {sev: sum(1 for f in findings if f.severity == sev) for sev in ("high", "medium", "low", "info")}
    add("## Summary")
    add("")
    add(" · ".join(f"{_BADGE[s]}: {n}" for s, n in counts.items()))
    add("")

    top = r.leads[:leads_mod.WHERE_TO_START]
    add("## Where to start")
    add("")
    if top:
        add("The most promising leads across all services, best first.")
        add("")
        for i, lead in enumerate(top, 1):
            add(f"{i}. **{lead.title}** ({lead.where})  ")
            add(f"   {lead.why}")
            if lead.command:
                add("")
                add(_indent(_fence(lead.command, "bash"), "   "))
            add("")
    else:
        add("_Nothing stood out._ Re-run without `--quick`/`-p` to sweep every port, "
            "and browse any web service by hand.")
        add("")

    add("## Open ports")
    add("")
    if r.services:
        add("| Port | Service | Version |")
        add("|---|---|---|")
        for s in r.services:
            name = s.name + (" (ssl)" if s.tunnel == "ssl" else "")
            add(f"| {s.label} | {_cell(name)} | {_cell(s.banner)} |")
    else:
        add("_No open ports found._ If the host is up, try `--ports` or a slower `--min-rate`.")
    add("")

    add("## Findings")
    add("")
    if not findings:
        add("_No findings._")
        add("")
    for f in findings:
        add(f"### {_BADGE[f.severity]} - {f.title} ({f.port}/tcp, `{f.module}`)")
        add("")
        if f.detail:
            add(f.detail)
            add("")
        body = _finding_body(f.data)
        if body:
            add(body)
            add("")

    rest = r.leads[leads_mod.WHERE_TO_START:]
    extra = leads_mod.other_hints(r)
    if rest or extra:
        add("## Other leads and ideas")
        add("")
        for lead in rest:
            cmd = f" `{lead.command}`" if lead.command else ""
            add(f"- **{lead.title}** ({lead.where}) - {lead.why}{cmd}")
        for h in extra:
            add(f"- {h}")
        add("")

    scripted = [s for s in r.services if s.scripts]
    if scripted:
        add("## Nmap script output")
        add("")
        for s in scripted:
            add(f"<details><summary>{s.label} {s.name}</summary>")
            add("")
            for sid, out in s.scripts.items():
                add(f"**{sid}**")
                add("")
                add(_fence(out or "(no output)"))
                add("")
            add("</details>")
            add("")

    if r.commands:
        add("## Commands run")
        add("")
        add(_fence("\n".join(r.commands)))
        add("")

    return "\n".join(lines).rstrip() + "\n"


def _finding_body(data: dict) -> str:
    if not data:
        return ""
    if "paths" in data:
        rows = ["| Path | Status | Size | Redirect |", "|---|---|---|---|"]
        for p in data["paths"][:200]:
            rows.append(f"| `{p['path']}` | {p['status']} | {p['size']} | {_cell(p.get('redirect', ''))} |")
        if len(data["paths"]) > 200:
            rows.append(f"| ... {len(data['paths']) - 200} more | | | |")
        return "\n".join(rows)
    for key in ("listing", "entries"):
        if key in data:
            return _fence("\n".join(data[key]))
    if "vhosts" in data:
        rows = ["| Virtual host | Status | Size |", "|---|---|---|"]
        rows += [f"| `{v['host']}` | {v['status']} | {v['size']} |" for v in data["vhosts"]]
        rows += ["", "Add them to `/etc/hosts`:", "", _fence(data["hosts_line"])]
        return "\n".join(rows)
    if "exploits" in data:
        rows = ["| EDB-ID | Title | Type | Verified |", "|---|---|---|---|"]
        rows += [f"| {e['edb_id']} | {_cell(e['title'])} | {e['type'] or '-'} | {'yes' if e['verified'] else 'no'} |"
                 for e in data["exploits"]]
        rows += ["", "Read one with `searchsploit -x <EDB-ID>`, copy it here with `searchsploit -m <EDB-ID>`."]
        return "\n".join(rows)
    if "shares" in data:
        rows = ["| Share | Type | Comment |", "|---|---|---|"]
        rows += [f"| `{s['name']}` | {s['type']} | {_cell(s['comment'])} |" for s in data["shares"]]
        return "\n".join(rows)
    return ""


def scrub(text: str) -> str:
    """Replace the user's home directory with '~' so shared reports don't leak local paths."""
    home = str(Path.home())
    if home and home != "/":
        text = text.replace(home, "~")
    return text


def write_reports(r: HostResult, outdir: Path) -> tuple[Path, Path]:
    outdir.mkdir(parents=True, exist_ok=True)
    md = outdir / "report.md"
    js = outdir / "findings.json"
    md.write_text(scrub(render_markdown(r)), encoding="utf-8")
    js.write_text(scrub(json.dumps(r.to_dict(), indent=2)), encoding="utf-8")
    return md, js
